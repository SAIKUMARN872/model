"use client";

import {
  CheckCircle2,
  Clock3,
  Download,
  FileText,
  IndianRupee,
  Printer,
  ReceiptText,
  ShieldCheck,
  WalletCards,
} from "lucide-react";

type ReceiptPanelProps = {
  transactionId: string;
  amount?: number;
  paymentMethod?: string;
  onContinue: () => void;
};

export default function ReceiptPanel({
  transactionId,
  amount = 499,
  paymentMethod = "UPI",
  onContinue,
}: ReceiptPanelProps) {
  const paidAt = new Date().toLocaleString(
    "en-IN",
    {
      dateStyle: "medium",
      timeStyle: "short",
    },
  );

  const handlePrint = () => {
    window.print();
  };

  const handleDownload = () => {
    const receiptText = [
      "ModelNow - Payment Receipt",
      "",
      `Transaction ID: ${transactionId}`,
      `Amount Paid: ₹${amount.toFixed(2)}`,
      `Payment Method: ${paymentMethod}`,
      "Payment Status: Successful",
      `Paid At: ${paidAt}`,
      "",
      "This receipt was generated by ModelNow.",
    ].join("\n");

    const blob = new Blob(
      [receiptText],
      {
        type: "text/plain;charset=utf-8",
      },
    );

    const url =
      URL.createObjectURL(blob);

    const anchor =
      document.createElement("a");

    anchor.href = url;
    anchor.download =
      `modelnow-receipt-${transactionId}.txt`;

    document.body.appendChild(
      anchor,
    );

    anchor.click();

    anchor.remove();

    URL.revokeObjectURL(url);
  };

  const handleContinue = () => {
    if (!transactionId) {
      return;
    }

    onContinue();
  };

  return (
    <section className="rounded-2xl border border-emerald-200 bg-emerald-50 p-4 shadow-sm sm:p-5">
      {/* Header */}
      <div className="flex items-start gap-3">
        <div className="flex h-10 w-10 shrink-0 items-center justify-center rounded-xl bg-emerald-100 text-emerald-600">
          <ReceiptText className="h-5 w-5" />
        </div>

        <div className="min-w-0 flex-1">
          <div className="flex flex-col gap-2 sm:flex-row sm:items-center sm:justify-between">
            <div>
              <h3 className="text-base font-semibold text-emerald-950">
                Invoice / Receipt
              </h3>

              <p className="mt-1 text-sm text-emerald-800">
                Your payment receipt has been generated successfully.
              </p>
            </div>

            <span className="inline-flex w-fit items-center gap-1.5 rounded-full bg-emerald-100 px-3 py-1 text-[10px] font-bold text-emerald-700">
              <CheckCircle2 className="h-3.5 w-3.5" />
              PAID
            </span>
          </div>
        </div>
      </div>

      {/* Receipt */}
      <div className="mt-5 rounded-xl border border-zinc-200 bg-white p-4">
        <div className="flex items-center justify-between gap-3 border-b border-zinc-100 pb-4">
          <div className="flex items-center gap-2">
            <FileText className="h-4 w-4 text-zinc-500" />

            <span className="text-sm font-medium text-zinc-700">
              Payment Receipt
            </span>
          </div>

          <span className="text-xs font-semibold text-emerald-600">
            Successful
          </span>
        </div>

        <div className="mt-4 space-y-3">
          <div className="flex flex-col gap-1 sm:flex-row sm:items-center sm:justify-between sm:gap-4">
            <span className="text-sm text-zinc-500">
              Transaction ID
            </span>

            <span className="break-all text-sm font-semibold text-zinc-900 sm:text-right">
              {transactionId}
            </span>
          </div>

          <div className="flex items-center justify-between gap-4">
            <span className="flex items-center gap-2 text-sm text-zinc-500">
              <IndianRupee className="h-4 w-4" />
              Amount Paid
            </span>

            <span className="text-base font-bold text-zinc-900">
              ₹{amount.toFixed(2)}
            </span>
          </div>

          <div className="flex items-center justify-between gap-4">
            <span className="flex items-center gap-2 text-sm text-zinc-500">
              <WalletCards className="h-4 w-4" />
              Payment Method
            </span>

            <span className="text-sm font-semibold text-zinc-900">
              {paymentMethod}
            </span>
          </div>

          <div className="flex flex-col gap-1 sm:flex-row sm:items-center sm:justify-between sm:gap-4">
            <span className="flex items-center gap-2 text-sm text-zinc-500">
              <Clock3 className="h-4 w-4" />
              Paid At
            </span>

            <span className="text-sm font-medium text-zinc-900 sm:text-right">
              {paidAt}
            </span>
          </div>
        </div>

        <div className="mt-4 flex items-start gap-2 rounded-lg bg-zinc-50 p-3">
          <ShieldCheck className="mt-0.5 h-4 w-4 shrink-0 text-emerald-600" />

          <p className="text-xs leading-5 text-zinc-600">
            Payment confirmation and receipt details are available for this
            completed transaction.
          </p>
        </div>
      </div>

      {/* Receipt actions */}
      <div className="mt-4 grid grid-cols-1 gap-2 sm:grid-cols-2">
        <button
          type="button"
          onClick={handleDownload}
          className="flex items-center justify-center gap-2 rounded-xl border border-zinc-200 bg-white px-4 py-2.5 text-sm font-medium text-zinc-700 transition hover:bg-zinc-50"
        >
          <Download className="h-4 w-4" />
          Download Receipt
        </button>

        <button
          type="button"
          onClick={handlePrint}
          className="flex items-center justify-center gap-2 rounded-xl border border-zinc-200 bg-white px-4 py-2.5 text-sm font-medium text-zinc-700 transition hover:bg-zinc-50"
        >
          <Printer className="h-4 w-4" />
          Print Receipt
        </button>
      </div>

      {/* Continue */}
      <button
        type="button"
        onClick={handleContinue}
        disabled={!transactionId}
        className="mt-3 flex w-full items-center justify-center rounded-xl bg-zinc-900 px-4 py-3 text-sm font-semibold text-white transition hover:bg-zinc-800 disabled:cursor-not-allowed disabled:opacity-50"
      >
        Continue to Verification
      </button>
    </section>
  );
}